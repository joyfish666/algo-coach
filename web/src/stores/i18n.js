function readStoredLang() {
  try {
    return localStorage.getItem(STORAGE_KEY)
  } catch {
    return null
  }
}

function detectLocale() {
  const lang = (navigator.language || 'en').toLowerCase()
  return lang.startsWith('zh') ? 'zh' : 'en'
}

export const useI18nStore = defineStore('i18n', {
  state: () => ({
    lang: readStoredLang() || detectLocale(),
  }),
  getters: {
    messages(state) {
      return MESSAGES[state.lang] || MESSAGES.en
    },
  },
  actions: {
    t(key, params) {
      let text = this.messages[key] ?? MESSAGES.en[key] ?? key
      if (params) {
        text = text.replace(/\{(\w+)\}/g, (match, name) =>
          params[name] !== undefined ? String(params[name]) : match
        )
      }
      return text
    },
    // dates follow the chosen UI language, not the browser locale - a zh
    // interface on an en-US browser would otherwise mix locales in one page
    formatDateTime(value) {
      const date = new Date(value)
      if (Number.isNaN(date.getTime())) return String(value ?? '')
      return date.toLocaleString(this.lang === 'zh' ? 'zh-CN' : 'en-US')
    },
    set(lang) {
      if (!MESSAGES[lang]) return
      this.lang = lang
      try {
        localStorage.setItem(STORAGE_KEY, lang)
      } catch {
      }
    },
  },
})
